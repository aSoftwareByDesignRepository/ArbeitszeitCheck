def catalog_for_lang(lang: str) -> dict[str, str]:
    out: dict[str, str] = {}
    out.update(UI.get(lang, {}))
    out.update(REGIONS.get(lang, {}))
    out.update(LAW_TERMS.get(lang, {}))
    out.update(EXTRA.get(lang, {}))
    return out


def main() -> None:
    proc = subprocess.run(
        ["php", str(ROOT / "scripts/l10n/extract-formal-gaps.php"), "--app=arbeitszeitcheck", "--json"],
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    gaps = json.loads(proc.stdout)
    catalog: dict[str, dict[str, str]] = {}

    for lang in LOCALES:
        cat = catalog_for_lang(lang)
        lang_cat: dict[str, str] = {}
        for key in gaps.get(lang, {}).get("identical", {}):
            if key in cat and cat[key]:
                lang_cat[key] = cat[key]
        catalog[lang] = lang_cat
        print(f"{lang}: {len(lang_cat)} identical catalog entries / {len(gaps.get(lang, {}).get('identical', {}))} gaps")

    (L10N / "_formal_catalog.json").write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
